def main() -> None:
    today_jst = datetime.now(JST).strftime("%Y-%m-%d")
    post = next((p for p in POSTS if p["date"] == today_jst), None)

    if post is None:
        print(f"今日({today_jst})の投稿はありません")
        return

    url = NOTE_URLS[post["category"]]
    text = post["text"].replace("{url}", url)

    print(f"投稿日: {today_jst}")
    print(f"カテゴリ: {post['category']}")
    print(f"文字数: {len(text)}")
    print("--- 投稿内容 ---")
    print(text[:100] + "...")

    from src.clients.threads import ThreadsClient

    client = ThreadsClient()
    remaining = client.check_limit()
    print(f"残り投稿可能数: {remaining}")
    if remaining <= 0:
        print("ERROR: 投稿制限に達しています")
        sys.exit(1)

    post_id = client.post(text)
    print(f"✅ 投稿完了: post_id={post_id}")


if __name__ == "__main__":
    main()
